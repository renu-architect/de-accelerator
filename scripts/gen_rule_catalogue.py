#!/usr/bin/env python3
"""Generate docs/architecture/modules/validation-rules.md from the live rule registry (no hand-maintained list)."""
from de_accelerator.metadata.validation import RULES
from de_accelerator.metadata.validation.engine import run_rules  # noqa: F401  (imports rule modules)
from de_accelerator.metadata.validation.engine import ValidationContext  # noqa: F401

import de_accelerator.metadata.validation.rules_compat, de_accelerator.metadata.validation.rules_policy  # noqa: F401,E401
import de_accelerator.metadata.validation.rules_referential, de_accelerator.metadata.validation.rules_semantic  # noqa: F401,E401

order = {"REFERENTIAL": 0, "SEMANTIC": 1, "POLICY": 2, "COMPAT": 3}
lines = ["# Validation rule catalogue (generated — do not edit)",
         "", "Generated by `scripts/gen_rule_catalogue.py` from the rule registry. Syntax findings `MDV-1xxx` come from the pack parser:",
         "1001 YAML/IO error · 1002 schema violation · 1003 bad item file/kind · 1004 duplicate key · 1005 manifest invalid/missing · "
         "1006 invalid environment override · 1007 invalid project layout.", "",
         f"Total registered rules: **{len(RULES)}**; each has a negative test in `tests/unit/test_validator.py` (enforced by a meta-test).", "",
         "| Code | Severity | Layer | Rule |", "|---|---|---|---|"]
for r in sorted(RULES, key=lambda r: (order[r.layer], r.code)):
    lines.append(f"| {r.code} | {r.severity} | {r.layer} | {r.title} |")
open("docs/architecture/modules/validation-rules.md", "w").write("\n".join(lines) + "\n")
print(len(RULES), "rules documented")
